// Fake gum for the commit review prompt. REVIEW_SCRIPT (or a single REVIEW_CHOICE)
// lists choices in order: each picks the menu label starting with that word, or
// simulates esc, ctrl-c, a broken prompt, or gum being unavailable (missing).
// A fake fm makes the Apple provider deterministic: FM_MODE=ready|unavailable|fail.
async function reviewGum(directory: string): Promise<NodeJS.ProcessEnv> {
  const bin = join(directory, 'review-bin');
  await mkdir(bin, { recursive: true });
  const log = join(directory, 'review-log');
  const step = join(directory, 'review-step');
  await writeFile(
    join(bin, 'gum'),
    `#!/usr/bin/env node
const fs = require('node:fs');
const args = process.argv.slice(2);
const script = (process.env.REVIEW_SCRIPT || process.env.REVIEW_CHOICE || 'edit').split(',');
if (args.includes('--version')) process.exit(script[0] === 'missing' ? 1 : 0);
if (args[0] === 'style') { console.log(args.at(-1)); process.exit(0); }
const labels = args.slice(args.indexOf('--') + 1);
const index = fs.existsSync(${JSON.stringify(step)}) ? Number(fs.readFileSync(${JSON.stringify(step)}, 'utf8')) : 0;
fs.writeFileSync(${JSON.stringify(step)}, String(index + 1));
fs.appendFileSync(${JSON.stringify(log)}, JSON.stringify({ command: args[0], labels, stdinTTY: process.stdin.isTTY }) + '\\n');
const choice = script[Math.min(index, script.length - 1)];
if (choice === 'esc') process.exit(1);
if (choice === 'ctrl-c') process.exit(130);
if (choice === 'broken') process.exit(2);
const label = labels.find(text => text.toLowerCase().startsWith(choice.toLowerCase()));
if (!label) process.exit(3);
console.log(label);
`,
    { mode: 0o700 },
  );
  await writeFile(
    join(bin, 'fm'),
    `#!/usr/bin/env node
const fs = require('node:fs');
const args = process.argv.slice(2);
const mode = process.env.FM_MODE || 'unavailable';
process.stdin.resume();
process.stdin.on('end', () => {
  if (args[0] === 'config') console.log('(none)');
  else if (args[0] === 'models') console.log(mode === 'unavailable' ? '✗ system (disabled)' : '✓ system (AFM model)');
  else if (args[0] === 'count-tokens') console.log('100');
  else if (args[0] === 'respond') {
    fs.appendFileSync(${JSON.stringify(join(directory, 'fm-calls'))}, 'respond\\n');
    if (mode === 'fail') process.exitCode = 1; else console.log('docs: regenerated by apple');
  }
});
`,
    { mode: 0o700 },
  );
  return { PATH: `${bin}:${process.env.PATH}` };
}

async function cli(directory: string, args: string[], env: NodeJS.ProcessEnv = {}, interactive = false) {
  const command = interactive ? 'python3' : entry;
  const parameters = interactive ? [tty, entry, ...args] : args;
  return await run(command, parameters, { cwd: directory, env: { ...process.env, ...env }, timeoutMs: 10_000 });
}

